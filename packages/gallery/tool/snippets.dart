// Writes lib/src/pages/snippets.g.dart: the Dart of the pages whose Code
// tab shows the live widget's own source. A region of a page's file between
//
//   // #code <name>
//   …
//   // #end
//
// becomes `const <name> = r'''…''';`, its lines without the indent they
// share, so that the Code is the code that runs and cannot drift from it.
//
//   dart run tool/snippets.dart            # write it
//   dart run tool/snippets.dart --check    # fail where it is stale
//
// `xtask gallery-snippets` runs it with --check.
import 'dart:io';

const _out = 'lib/src/pages/snippets.g.dart';

void main(List<String> args) {
  if (!File('pubspec.yaml').readAsStringSync().startsWith('name: gallery')) {
    stderr.writeln('run it from packages/gallery');
    exit(64);
  }
  final text = snippetsLibrary(Directory('lib/src/pages'));
  final file = File(_out);
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != text) {
      stderr.writeln(
        '$_out is stale: dart run tool/snippets.dart writes it again',
      );
      exit(1);
    }
    return;
  }
  file.writeAsStringSync(text);
}

/// The library of the regions in the files under [dir], by their names.
String snippetsLibrary(Directory dir) {
  final regions = <String, (String, String)>{};
  final files = [
    for (final f in dir.listSync(recursive: true))
      if (f is File && f.path.endsWith('.dart') && !f.path.endsWith('.g.dart'))
        f,
  ]..sort((a, b) => a.path.compareTo(b.path));
  for (final f in files) {
    for (final (name, code) in regionsOf(f.readAsStringSync())) {
      if (regions[name] case (final other, _)) {
        throw StateError('$name is in ${f.path} and in $other');
      }
      regions[name] = (f.path, code);
    }
  }
  final names = regions.keys.toList()..sort();
  return [
    '// Generated by tool/snippets.dart from the regions of the pages',
    '// marked `// #code <name>`: the Code tabs that show the source that',
    '// runs. Do not edit; edit the region.',
    '',
    for (final name in names) ...[
      '/// The Code of `${regions[name]!.$1}`, its region `$name`.',
      "const $name = r'''",
      "${regions[name]!.$2}''';",
      '',
    ],
  ].join('\n');
}

/// The regions of [source]: each `// #code <name>` to its `// #end`, its
/// lines without the indent they share.
List<(String, String)> regionsOf(String source) {
  final out = <(String, String)>[];
  final lines = source.split('\n');
  for (var i = 0; i < lines.length; i++) {
    final m = RegExp(r'^\s*// #code (\w+)$').firstMatch(lines[i]);
    if (m == null) {
      continue;
    }
    final end = lines.indexWhere((l) => l.trim() == '// #end', i + 1);
    if (end < 0) {
      throw StateError('${m[1]} has no // #end');
    }
    final body = lines.sublist(i + 1, end);
    final indent = body
        .where((l) => l.trim().isNotEmpty)
        .map((l) => l.length - l.trimLeft().length)
        .fold<int?>(null, (a, n) => a == null || n < a ? n : a);
    final code = [
      for (final l in body)
        if (l.trim().isEmpty) '' else l.substring(indent ?? 0),
    ].join('\n');
    if (code.contains("'''")) {
      throw StateError("${m[1]} has ''' in it, which its raw string cannot");
    }
    out.add((m[1]!, code));
    i = end;
  }
  return out;
}
