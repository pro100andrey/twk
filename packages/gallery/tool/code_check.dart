// Holds each page's Code tab to its stage: the Code, made into a program,
// run in twk's tester on a terminal the size of the stage's room, in the
// page's theme, to the route's time; its cells against the stage's, cell
// by cell (the glyph, the colours and the attributes).
//
//   dart run tool/code_check.dart            # every page, dark, 120x36, 2 s
//   dart run tool/code_check.dart '#/controls/button?o=style:danger'
//
// Run from packages/gallery. It writes .dart_tool/code_check/: stages.json
// (what tool/code_check/stages.dart read of the stages), gen/ (the package
// the Codes are made into, tool/code_check/wrap.dart, and the program
// that runs them, tool/code_check/harness.dart), report.md. It fails when
// a page's Code does not compile, fails in twk, or differs from its stage
// where tool/code_check/known.dart does not expect it to.
import 'dart:convert';
import 'dart:io';

import 'package:gallery/src/shell/tokens.dart' show galleryThemes;
import 'package:twk/twk.dart';

import 'code_check/known.dart';
import 'code_check/wrap.dart';

const _out = '.dart_tool/code_check';

void main(List<String> args) {
  if (!File('pubspec.yaml').readAsStringSync().startsWith('name: gallery')) {
    stderr.writeln('run it from packages/gallery');
    exit(64);
  }
  final started = DateTime.now();
  Directory(_out).createSync(recursive: true);
  const stagesFile = '$_out/stages.json';
  _run('dart', ['run', 'tool/code_check/stages.dart', stagesFile, ...args]);
  final stages = (jsonDecode(File(stagesFile).readAsStringSync()) as Map)
      .cast<String, Map<String, Object?>>();

  final gen = Directory('$_out/gen');
  final lib = Directory('${gen.path}/lib');
  if (lib.existsSync()) {
    lib.deleteSync(recursive: true);
  }
  lib.createSync(recursive: true);
  Directory('${gen.path}/bin').createSync(recursive: true);
  _writePackage(gen.path);

  // a library for each Code, by id
  final ids = <String, String>{};
  for (final (i, MapEntry(key: route, value: s)) in stages.entries.indexed) {
    if (s['code'] case final String code when s['cells'] != null) {
      final id = 'p${'$i'.padLeft(3, '0')}';
      ids[route] = id;
      final wrapped = wrap(code);
      File(
        '${lib.path}/$id.dart',
      ).writeAsStringSync('// $route\n${wrapped.dart}\n');
      for (final MapEntry(key: path, value: text) in wrapped.files.entries) {
        File('${gen.path}/$path')
          ..parent.createSync(recursive: true)
          ..writeAsStringSync(text);
      }
      if (wrapped.mode == WrapMode.cli) {
        Directory('${lib.path}/cli').createSync(recursive: true);
        File('lib/cli/run.dart').copySync('${lib.path}/cli/run.dart');
      }
    }
  }
  if (stages.values.any(
    (s) => '${s['code']}'.contains("import 'scripted_shell.dart'"),
  )) {
    File('lib/scripted_shell.dart').copySync('${lib.path}/scripted_shell.dart');
  }
  final assets = Directory('lib/src/pages/assets');
  if (assets.existsSync()) {
    _copyDir(assets, Directory('${gen.path}/assets'));
  }
  _pubGet(gen.path);
  final errors = _analyze(gen.path);

  final entries = [
    for (final MapEntry(key: route, value: id) in ids.entries)
      if (!errors.containsKey(id)) (route, id, stages[route]!),
  ];
  File('${gen.path}/bin/render.dart').writeAsStringSync(
    [
      '// Generated by tool/code_check.dart: runs the Code of each page.',
      "import 'package:code_check_gen/harness.dart';",
      for (final (_, id, _) in entries)
        "import 'package:code_check_gen/$id.dart' as $id;",
      '',
      'void main() => renderAll([',
      for (final (_, id, s) in entries) _entry(id, s),
      "], 'cells.json');",
      '',
    ].join('\n'),
  );
  _run('dart', ['run', 'bin/render.dart'], dir: gen.path, tests: true);
  final results = (jsonDecode(
    File('${gen.path}/cells.json').readAsStringSync(),
  ) as Map).cast<String, Map<String, Object?>>();

  final rows = [
    for (final MapEntry(key: route, value: s) in stages.entries)
      _row(route, s, ids[route], errors, results),
  ];
  final seconds = DateTime.now().difference(started).inSeconds;
  final report = _report(rows, seconds);
  File('$_out/report.md').writeAsStringSync(report);
  final count = <String, int>{};
  for (final r in rows) {
    count[r.status] = (count[r.status] ?? 0) + 1;
  }
  stdout.writeln(
    '${rows.length} pages: '
    '${[for (final s in _statuses)
      if (count[s] case final n?) '$n $s'].join(', ')}'
    ' ($seconds s)\nreport: $_out/report.md',
  );
  for (final r in rows.where((r) => _failing.contains(r.status))) {
    stdout.writeln('\n${r.key} ${r.status}: ${r.cause}');
    for (final c in r.cells.take(6)) {
      stdout.writeln('  $c');
    }
  }
  final stale = [
    for (final r in rows)
      if (r.status == 'matches' && knownCode.containsKey(r.key)) r.key,
  ];
  if (stale.isNotEmpty) {
    stdout.writeln(
      '\nmatch now, their entries in known.dart can go: ${stale.join(', ')}',
    );
  }
  exit(rows.any((r) => _failing.contains(r.status)) ? 1 : 0);
}

const _statuses = [
  'matches',
  'expected',
  'differs',
  'does not compile',
  'twk failed',
  'not comparable',
];

const _failing = {'differs', 'does not compile', 'twk failed'};

/// The line of bin/render.dart that runs library [id] as stage [s] asks.
String _entry(String id, Map<String, Object?> s) {
  final room = s['room']! as Map;
  final keys = (s['keys']! as List).cast<String>();
  final type = s['type']! as String;
  String str(String v) => jsonEncode(v).replaceAll(r'$', r'\$');
  return [
    "  Entry('$id', $id.codeWidget, theme: '${s['theme']}', ",
    'width: ${room['w']}, height: ${room['h']}, ms: ${s['ms']}',
    if (keys.isNotEmpty) ', keys: [${keys.map(str).join(', ')}]',
    if (type.isNotEmpty) ', type: ${str(type)}',
    if (s['terminal'] == true) ', terminal: true',
    '),',
  ].join();
}

/// A page's result: its key and route, its status, why, and its first
/// differing cells.
typedef _Row = ({
  String key,
  String route,
  String status,
  String cause,
  List<String> cells,
});

_Row _row(
  String route,
  Map<String, Object?> s,
  String? id,
  Map<String, List<String>> errors,
  Map<String, Map<String, Object?>> results,
) {
  final key = '${s['key'] ?? route}';
  _Row row(String status, [String cause = '', List<String> cells = const []]) =>
      (key: key, route: route, status: status, cause: cause, cells: cells);
  if (s['error'] case final String e) {
    return row('not comparable', 'the stage: $e');
  }
  if (s['code'] == null) {
    return row('not comparable', 'no Code tab');
  }
  if (s['noApp'] == true) {
    return row('not comparable', "the stage shows no Code's app at this time");
  }
  if (id == null) {
    return row('not comparable', 'the stage was not read');
  }
  if (errors[id] case final e?) {
    return row('does not compile', e.take(3).join('; '));
  }
  final r = results[id];
  if (r == null || r['error'] != null || r['cells'] == null) {
    return row('twk failed', '${r?['error'] ?? 'no result'}');
  }
  if (r['errorWidgets'] case final List<Object?> w
      when !'${s['code']}'.contains('ErrorWidget')) {
    return row('twk failed', 'ErrorWidget: ${'${w.first}'.split('\n').first}');
  }
  final theme = galleryThemes[s['theme']]!.$2;
  final c = _compare(
    _cells(s['cells']!),
    _cells(r['cells']!),
    _rgbOr(theme.text.fg, 0xFFFFFF),
    _rgbOr(theme.background.bg, 0),
  );
  if (c.differing == 0) {
    return row('matches');
  }
  final rect = r['rect']! as Map;
  final stage = s['rect']! as Map;
  final sized = stage['w'] == rect['w'] && stage['h'] == rect['h'];
  final layout =
      'layout: ${stage['w']}×${stage['h']} on the stage, '
      '${rect['w']}×${rect['h']} in twk';
  final cause = [
    if (!sized) layout,
    for (final MapEntry(key: k, value: n) in c.kinds.entries)
      if (n > 0) '$k $n',
  ].join('; ');
  if (knownCode[key] case final why?) {
    return row('expected', '$why — $cause', c.cells);
  }
  return row('differs', '${c.differing} cells: $cause', c.cells);
}

/// The RGB of [color], [fallback] for the default or a palette color.
int _rgbOr(Color? color, int fallback) {
  final v = color?.value ?? 0;
  return v & 0x1000000 != 0 ? v & 0xFFFFFF : fallback;
}

/// A cell as both sides write it: text, fg, bg, attributes, role.
typedef _Cell = (String, int, int, int, int);

List<List<_Cell>> _cells(Object json) => [
  for (final row in (json as List).cast<List<Object?>>())
    [
      for (final c in row.cast<List<Object?>>())
        (
          c[0]! as String,
          c[1]! as int,
          c[2]! as int,
          c[3]! as int,
          c[4]! as int,
        ),
    ],
];

/// The cells of the stage [a] and of the Code [b] compared from their top
/// left corners over the larger of the two, a cell outside one taken as a
/// blank of the stage: a cell differs in its glyph, its colours (the
/// default ones as [text] and [background], reverse video resolved) or
/// its attributes; a blank only in its background, unless it has a line
/// that shows on a blank.
({int differing, Map<String, int> kinds, List<String> cells}) _compare(
  List<List<_Cell>> a,
  List<List<_Cell>> b,
  int text,
  int background,
) {
  const lines = Attr.underlineMask | Attr.strike | Attr.overline;
  (String, int, int, int) shown(_Cell? c) {
    if (c == null) {
      return (' ', text, background, 0);
    }
    final (t, fg0, bg0, at, role) = c;
    // a 24-bit colour as its RGB, the default one as [dflt], a palette
    // colour as it is
    int rgb(int v, int dflt) => v == 0
        ? dflt
        : v & 0x1000000 != 0
        ? v & 0xFFFFFF
        : v;
    var fg = rgb(fg0, text);
    var bg = rgb(bg0, background);
    if (at & Attr.reverse != 0) {
      (fg, bg) = (bg, fg);
    }
    return (role == -1 ? '' : t, fg, bg, at & ~Attr.reverse);
  }

  bool blank((String, int, int, int) c) =>
      (c.$1 == ' ' || c.$1.isEmpty) && c.$4 & lines == 0;
  String name((String, int, int, int) c) =>
      "'${c.$1}' ${_hex(c.$2)} on ${_hex(c.$3)} ${c.$4}";

  final h = a.length > b.length ? a.length : b.length;
  final w = [
    for (final rows in [a, b])
      if (rows.isNotEmpty) rows.first.length,
  ].fold(0, (m, n) => n > m ? n : m);
  final kinds = {'glyph': 0, 'fg': 0, 'bg': 0, 'attr': 0, 'outside': 0};
  final cells = <String>[];
  var differing = 0;
  for (var y = 0; y < h; y++) {
    for (var x = 0; x < w; x++) {
      final ca = y < a.length && x < a[y].length ? a[y][x] : null;
      final cb = y < b.length && x < b[y].length ? b[y][x] : null;
      final sa = shown(ca);
      final sb = shown(cb);
      final k = <String>[
        if (blank(sa) && blank(sb)) ...[
          if (sa.$3 != sb.$3) 'bg',
        ] else ...[
          if (sa.$1 != sb.$1) 'glyph',
          if (sa.$2 != sb.$2) 'fg',
          if (sa.$3 != sb.$3) 'bg',
          if (sa.$4 != sb.$4) 'attr',
        ],
      ];
      if (k.isEmpty) {
        continue;
      }
      if (ca == null || cb == null) {
        k.add('outside');
      }
      differing++;
      for (final kind in k) {
        kinds[kind] = kinds[kind]! + 1;
      }
      if (cells.length < 12) {
        cells.add(
          '($x, $y) ${k.join(',')}: stage ${name(sa)} | Code ${name(sb)}',
        );
      }
    }
  }
  return (differing: differing, kinds: kinds, cells: cells);
}

String _hex(int rgb) => rgb & 0x2000000 != 0 && rgb & 0x1000000 == 0
    ? 'indexed(${rgb & 0xFF})'
    : '#${(rgb & 0xFFFFFF).toRadixString(16).padLeft(6, '0')}';

String _report(List<_Row> rows, int seconds) {
  String cell(String s) => s.replaceAll('|', r'\|').replaceAll('\n', ' ');
  return [
    "# The gallery: each page's Code against its stage",
    '',
    '${DateTime.now().toUtc().toIso8601String()}, $seconds s.',
    '',
    '| page | route | status | cause |',
    '| --- | --- | --- | --- |',
    for (final r in rows)
      '| ${r.key} | `${r.route}` | ${r.status} | ${cell(r.cause)} |',
    '',
    '## First differing cells',
    for (final r in rows)
      if (r.cells.isNotEmpty) ...[
        '',
        '### ${r.key} (${r.status})',
        '',
        for (final c in r.cells) '- $c',
      ],
    '',
  ].join('\n');
}

/// Writes the pubspec, the analysis options and the harness of the
/// package at [dir].
void _writePackage(String dir) {
  final root = Directory.current.parent.parent.absolute.path;
  String pkg(String p) => '$root/$p';
  File('$dir/pubspec.yaml').writeAsStringSync(
    [
      'name: code_check_gen',
      'publish_to: none',
      'environment:',
      '  sdk: ^3.13.5',
      'dependencies:',
      '  test: ^1.33.0',
      '  twk: any',
      '  twk_core: any',
      '  twk_rich: {path: ${pkg('packages/twk_rich')}}',
      '  twk_term: {path: ${pkg('packages/twk_term')}}',
      '  twk_test: {path: ${pkg('packages/twk_test')}}',
      // twk and twk_test take the packages under them by version, the
      // others by path: the checkout's
      'dependency_overrides:',
      '  twk: {path: ${pkg('packages/twk')}}',
      '  twk_core: {path: ${pkg('packages/twk_core')}}',
      '',
    ].join('\n'),
  );
  // the Codes are judged by whether they compile, not by the lints
  File('$dir/analysis_options.yaml').writeAsStringSync(
    [
      'analyzer:',
      '  errors:',
      for (final e in const [
        'unused_import',
        'unused_element',
        'unused_field',
        'unused_local_variable',
        'dead_code',
        'unused_element_parameter',
        'unnecessary_import',
      ])
        '    $e: ignore',
      '',
    ].join('\n'),
  );
  File(
    'tool/code_check/harness.dart',
  ).copySync('$dir/lib/harness.dart');
}

void _copyDir(Directory from, Directory to) {
  to.createSync(recursive: true);
  for (final e in from.listSync()) {
    final name = e.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
    if (e is Directory) {
      _copyDir(e, Directory('${to.path}/$name'));
    } else if (e is File) {
      e.copySync('${to.path}/$name');
    }
  }
}

/// `dart pub get` in [dir], offline first.
void _pubGet(String dir) {
  for (final args in const [
    ['pub', 'get', '--offline'],
    ['pub', 'get'],
  ]) {
    final r = Process.runSync('dart', args, workingDirectory: dir);
    if (r.exitCode == 0) {
      return;
    }
  }
  throw StateError('dart pub get failed in $dir');
}

/// The errors `dart analyze` finds in the libraries of [dir], by id.
Map<String, List<String>> _analyze(String dir) {
  final r = Process.runSync('dart', [
    'analyze',
    '--format=machine',
    'lib',
  ], workingDirectory: dir);
  final out = <String, List<String>>{};
  for (final line in '${r.stdout}\n${r.stderr}'.split('\n')) {
    // SEVERITY|TYPE|CODE|FILE|LINE|COL|LENGTH|MESSAGE
    final f = line.split('|');
    if (f.length < 8 || f[0] != 'ERROR') {
      continue;
    }
    final m = RegExp(r'/(p\d+)\.dart$').firstMatch(f[3]);
    if (m == null) {
      continue;
    }
    (out[m[1]!] ??= []).add(
      '${f[4]}:${f[5]} ${f.sublist(7).join('|').replaceAll(r'\', '')}',
    );
  }
  return out;
}

/// Runs [exe] with [args] in [dir], its output shown only when it fails;
/// with [tests], a test that failed in it is not its failure (each writes
/// what it found).
void _run(String exe, List<String> args, {String? dir, bool tests = false}) {
  final r = Process.runSync(exe, args, workingDirectory: dir);
  if (r.exitCode != 0 && !(tests && '${r.stdout}'.contains('Some tests'))) {
    stderr
      ..writeln('$exe ${args.join(' ')} failed (${r.exitCode}):')
      ..writeln(r.stdout)
      ..writeln(r.stderr);
    exit(1);
  }
}
