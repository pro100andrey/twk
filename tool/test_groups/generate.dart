// Prototype (task test-groups-prototype): writes entry points that join a
// package's test files, so `dart test` compiles, loads and JITs one isolate
// per group instead of one per file.
//
//   dart run tool/test_groups/generate.dart [options]
//
//   --package=packages/twk   the package whose test/ is joined
//   --groups=8               how many entry points
//   --times=<file>           the output of `dart test --reporter=json`, run
//                            earlier; the files are balanced by the time
//                            their tests took (their size when absent)
//   --shuffle=<seed>         a shuffled assignment of the files to groups
//   --out=<dir>              default <package>/.dart_tool/test_groups
//
// Each entry imports its files with a prefix and calls each `main()` inside
// `group('<file path>', ...)`, so a failure still names its file. A file the
// join could change the meaning of stays out and runs as it is: the reason
// is in `excluded.txt` beside the entries. `args.txt` is what to pass to
// `dart test` (groups first, then the files left out).
//
// The generated files are not checked in; `dart test <file>` is unchanged
// for every file.
import 'dart:convert';
import 'dart:io';
import 'dart:math';

/// Reasons a file stays out, each a pattern in the file's source. These are
/// the things a join changes: where the file is told to run, what it
/// measures about its own place, the isolate it shares with others.
final _reasons = <String, RegExp>{
  'annotation (@TestOn, @Tags, @Timeout, @Skip)': RegExp(
    r'^@(TestOn|Tags|Timeout|Skip)\b',
    multiLine: true,
  ),
  'async main': RegExp(r'\bmain\(\s*\)\s*async\b|Future<void>\s+main\('),
  'main is not `void main()`': RegExp(r"^(?![\s\S]*\nvoid main\(\)\s*\{)"),
  'Platform.script': RegExp(r'Platform\.script'),
  'Isolate lookups': RegExp(r'\bIsolate\.'),
  'reads a stack of its own (StackTrace.current, Trace)': RegExp(
    r'StackTrace\.current|\bTrace\.|Frame\.caller|\.stackTrace\b',
  ),
  'starts a process': RegExp(
    r'\bProcess\.(run|start)|\brunProcess\(|\bstartProcess\(',
  ),
};

/// Files left out by hand, for what a pattern cannot see: the value says
/// what in the file a join would change.
const _byHand = <String, String>{};

Future<void> main(List<String> argv) async {
  final opts = {
    for (final a in argv)
      if (a.startsWith('--'))
        a.substring(2).split('=').first: a.contains('=')
            ? a.substring(a.indexOf('=') + 1)
            : 'true',
  };
  final pkg = opts['package'] ?? 'packages/twk';
  final groups = int.parse(opts['groups'] ?? '8');
  final out = opts['out'] ?? '$pkg/.dart_tool/test_groups';
  final shuffle = opts['shuffle'];

  final files = [
    for (final e in Directory('$pkg/test').listSync(recursive: true))
      if (e is File && e.path.endsWith('_test.dart'))
        e.path.substring(pkg.length + 1),
  ]..sort();

  final times = _times(opts['times'], pkg);
  final included = <String>[];
  final excluded = <String, String>{};
  for (final f in files) {
    final src = File('$pkg/$f').readAsStringSync();
    final reasons = [
      for (final r in _reasons.entries)
        if (r.value.hasMatch(src)) r.key,
      if (src.contains(f)) 'names its own path',
      ?_byHand[f],
    ];
    if (reasons.isEmpty) {
      included.add(f);
    } else {
      excluded[f] = reasons.join('; ');
    }
  }

  double weight(String f) => times[f] ?? File('$pkg/$f').lengthSync() / 20000;
  if (shuffle != null) {
    included.shuffle(Random(int.parse(shuffle)));
  } else {
    included.sort((a, b) => weight(b).compareTo(weight(a)));
  }
  final load = List.filled(groups, 0.0);
  final members = List.generate(groups, (_) => <String>[]);
  // longest first (or in the shuffled order), each to the lightest group
  for (final f in included) {
    var best = 0;
    for (var i = 1; i < groups; i++) {
      if (load[i] < load[best]) best = i;
    }
    members[best].add(f);
    load[best] += weight(f);
  }

  final dir = Directory(out);
  if (dir.existsSync()) dir.deleteSync(recursive: true);
  dir.createSync(recursive: true);
  // from `<pkg>/<out>/` back to `<pkg>/test/`
  final depth = out.substring(pkg.length + 1).split('/').length;
  final up = '../' * depth;
  final args = <String>[];
  for (var g = 0; g < groups; g++) {
    if (members[g].isEmpty) continue;
    members[g].sort();
    final b = StringBuffer()
      ..writeln('// Generated by tool/test_groups/generate.dart: do not edit.')
      ..writeln("import 'package:test/test.dart';");
    for (var i = 0; i < members[g].length; i++) {
      b.writeln("import '$up${members[g][i]}' as f$i;");
    }
    b.writeln('\nvoid main() {');
    for (var i = 0; i < members[g].length; i++) {
      b.writeln("  group('${members[g][i]}', f$i.main);");
    }
    b.writeln('}');
    final name = '$out/group_${g}_test.dart';
    File(name).writeAsStringSync('$b');
    args.add(name.substring(pkg.length + 1));
  }
  // a file tagged `process` runs apart (`process-test`), a `@TestOn` that is
  // not this platform's runs nowhere: neither is passed
  final leftover = <String>[];
  for (final f in excluded.keys) {
    final src = File('$pkg/$f').readAsStringSync();
    final process = RegExp(
      r'''^@Tags\(\[.*'process'.*\]\)''',
      multiLine: true,
    );
    if (process.hasMatch(src)) continue;
    if (RegExp(r"^@TestOn\('mac-os'\)", multiLine: true).hasMatch(src)) {
      continue;
    }
    leftover.add(f);
  }
  File('$out/args.txt').writeAsStringSync([...args, ...leftover].join(' '));
  File('$out/excluded.txt').writeAsStringSync(
    [for (final e in excluded.entries) '${e.key}\t${e.value}'].join('\n'),
  );
  File('$out/groups.json').writeAsStringSync(
    const JsonEncoder.withIndent('  ').convert({
      'groups': {
        for (var g = 0; g < groups; g++)
          'group_$g': {'load': load[g], 'files': members[g]},
      },
      'leftover': leftover,
    }),
  );
  stdout.writeln(
    '${included.length} files in ${args.length} groups '
    '(load ${load.map((l) => l.toStringAsFixed(1)).join(' ')}), '
    '${excluded.length} left out, ${leftover.length} of them run as they are.',
  );
}

/// Seconds the tests of each file took, from a json reporter log.
Map<String, double> _times(String? log, String pkg) {
  final times = <String, double>{};
  if (log == null) return times;
  final suites = <int, String>{};
  final tests = <int, (int, int)>{};
  for (final line in File(log).readAsLinesSync()) {
    if (!line.startsWith('{')) continue;
    final Map<String, dynamic> e;
    try {
      e = jsonDecode(line) as Map<String, dynamic>;
    } on FormatException {
      continue;
    }
    switch (e['type']) {
      case 'suite':
        final s = e['suite'] as Map<String, dynamic>;
        suites[s['id'] as int] = s['path'] as String;
      case 'testStart':
        final t = e['test'] as Map<String, dynamic>;
        tests[t['id'] as int] = (t['suiteID'] as int, e['time'] as int);
      case 'testDone':
        final started = tests[e['testID']];
        final suite = started == null ? null : suites[started.$1];
        if (suite == null) continue;
        final rel = suite.startsWith('$pkg/')
            ? suite.substring(pkg.length + 1)
            : suite;
        times[rel] =
            (times[rel] ?? 0) + ((e['time'] as int) - started!.$2) / 1000;
      default:
    }
  }
  return times;
}
